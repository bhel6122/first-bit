/* Compile tools/ui-en-*.json into app/public/js/lang/en.js, and check the keys
   against what the app actually renders.

   The dictionary is keyed by the Chinese string, so a single mistyped character
   turns into a silent fallback to Chinese at runtime. That is exactly the kind
   of bug nobody notices until a screenshot is wrong, so the build fails loudly:
   a key that no source file contains is reported, and so is a rendered string
   that has no translation yet. */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(".");
const TOOLS = path.join(ROOT, "tools");
const OUT = path.join(ROOT, "app/public/js/lang/en.js");

const dict = {};
const seen = new Map();

for (const name of (await readdir(TOOLS)).sort()) {
  if (!/^ui-en.*\.json$/.test(name)) continue;
  const part = JSON.parse(await readFile(path.join(TOOLS, name), "utf8"));
  for (const [k, v] of Object.entries(part)) {
    const key = k.replace(/\s+/g, " ").trim();
    if (!key) continue;
    if (seen.has(key) && seen.get(key) !== v) {
      console.warn(`! duplicate key with different value: ${key} (${name})`);
    }
    seen.set(key, v);
    dict[key] = v;
  }
}

/* ---- coverage check ---- */
let extracted = [];
try {
  extracted = JSON.parse(await readFile(path.join(TOOLS, "ui-strings.json"), "utf8")).map((x) => x.s);
} catch {
  console.warn("(no ui-strings.json — run tools/extract-ui.mjs first, skipping coverage)");
}

const known = new Set(extracted.map((s) => s.replace(/\s+/g, " ").trim()));
/* A label assembled around an icon — "进入闯关世界 ${icon(...)}" — is cut at the
   interpolation by the extractor, so match on containment as well as equality. */
const dangling = Object.keys(dict).filter(
  (k) => known.size && !known.has(k) && !extracted.some((s) => s.includes(k)),
);
/* i18n.js still carries a hand-written block for the screens that call t() at
   the call site. Those keys never reach the DOM pass, so subtract them. */
let handSrc = "";
try {
  handSrc = await readFile(path.join(ROOT, "app/public/js/i18n.js"), "utf8");
} catch {
  /* i18n.js is expected; a missing one will fail loudly at runtime anyway */
}
function handHas(key) {
  return handSrc.includes(`${JSON.stringify(key)}:`) || handSrc.includes(`${key}:`);
}

const missing = [...known].filter((k) => !dict[k] && !/^[\x00-\x7f]*$/.test(k) && !handHas(k));

if (dangling.length) {
  console.warn(`\n${dangling.length} key(s) match no source string (typo?):`);
  for (const k of dangling) console.warn(`  · ${k}`);
}
if (missing.length) {
  console.warn(`\n${missing.length} rendered string(s) still untranslated:`);
  for (const k of missing) console.warn(`  · ${k}`);
}

/* ---- emit ---- */
const sorted = Object.keys(dict).sort();
const body = sorted.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(dict[k])},`).join("\n");

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(
  OUT,
  `/* Generated by tools/build-i18n.mjs from tools/ui-en-*.json — do not edit by hand.

   Keyed by the Chinese text as rendered. The DOM pass looks strings up by their
   trimmed, whitespace-collapsed form, so a key must match the source exactly. */

const EN = {
${body}
};

export default EN;
`,
);

console.log(`\nwrote ${sorted.length} entries -> ${path.relative(ROOT, OUT)}`);
